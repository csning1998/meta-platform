func testRecords(t *testing.T) []Record {
	t.Helper()
	return []Record{
		{mustParseAddr(t, "172.16.125.250"), []string{"meta-platform-spire-parent.dev"}},
		{mustParseAddr(t, "172.16.127.250"), []string{"meta-platform-vault.dev", "vault.dev"}},
	}
}

// testBlock is the managed block which testRecords render.
const testBlock = BeginMark + "\n" +
	"172.16.125.250 meta-platform-spire-parent.dev\n" +
	"172.16.127.250 meta-platform-vault.dev vault.dev\n" +
	EndMark + "\n"

func TestRewriteHostsBlock_ReplacesOrAppendsManagedBlock(t *testing.T) {
	cases := []struct {
		name    string
		current string
		want    string
	}{
		{
			name: "block in the middle with the marker of the shell script",
			current: "127.0.0.1 localhost\n" +
				"# BEGIN meta-platform: generated by tools/sync-etc-hosts.sh from the libvirt DNS records\n" +
				"172.16.1.1 meta-platform-stale.dev\n" +
				EndMark + "\n" +
				"192.168.1.10 nas.home\n",
			want: "127.0.0.1 localhost\n" + testBlock + "192.168.1.10 nas.home\n",
		},
		{
			name:    "block absent",
			current: "127.0.0.1 localhost\n::1 localhost\n",
			want:    "127.0.0.1 localhost\n::1 localhost\n\n" + testBlock,
		},
		{
			name:    "block absent with trailing blank lines",
			current: "127.0.0.1 localhost\n\n\n",
			want:    "127.0.0.1 localhost\n\n" + testBlock,
		},
		{
			name:    "block absent without final newline",
			current: "127.0.0.1 localhost",
			want:    "127.0.0.1 localhost\n\n" + testBlock,
		},
		{
			name:    "empty file",
			current: "",
			want:    testBlock,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := RewriteHostsBlock(c.current, testRecords(t))
			if err != nil {
				t.Fatalf("RewriteHostsBlock: %v", err)
			}
			if got != c.want {
				t.Errorf("RewriteHostsBlock =\n%s\nwant\n%s", got, c.want)
			}
			again, err := RewriteHostsBlock(got, testRecords(t))
			if err != nil || again != got {
				t.Errorf("second RewriteHostsBlock = %q, %v, want the first result unchanged", again, err)
			}
		})
	}
}

func TestRewriteHostsBlock_RejectsMalformedBlock(t *testing.T) {
	for name, current := range map[string]string{
		"begin without end": "127.0.0.1 localhost\n" + BeginMark + "\n172.16.1.1 meta-platform-x.dev\n192.168.1.10 nas.home\n",
		"end without begin": "127.0.0.1 localhost\n" + EndMark + "\n",
		"two blocks":        testBlock + "127.0.0.1 localhost\n" + testBlock,
		"nested begin":      BeginMark + "\n" + BeginMark + "\n" + EndMark + "\n",
	} {
		t.Run(name, func(t *testing.T) {
			_, err := RewriteHostsBlock(current, testRecords(t))
			if !errors.Is(err, ErrMalformedBlock) {
				t.Errorf("RewriteHostsBlock error = %v, want ErrMalformedBlock", err)
			}
		})
	}
}

