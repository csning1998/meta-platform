func TestMergeRecords_MergesAndSortsByAddress(t *testing.T) {
	vault := mustParseAddr(t, "172.16.127.250")
	low := mustParseAddr(t, "172.16.9.1")
	high := mustParseAddr(t, "172.16.10.1")

	got := MergeRecords(
		[]Record{{high, []string{"meta-platform-b.dev"}}, {vault, []string{"meta-platform-vault.dev", "vault.dev"}}},
		[]Record{{vault, []string{"meta-platform-vault.dev", "vault.dev"}}, {low, []string{"meta-platform-a.dev"}}},
		[]Record{{vault, []string{"vault.dev", "meta-platform-vault-alias.dev"}}},
	)
	assertRecords(t, got, []Record{
		{low, []string{"meta-platform-a.dev"}},
		{high, []string{"meta-platform-b.dev"}},
		{vault, []string{"meta-platform-vault.dev", "vault.dev", "meta-platform-vault-alias.dev"}},
	})
}

