const prefix = "meta-platform-"

// networkXML mirrors the dns element of virsh net-dumpxml for a network of the project.
const networkXML = `<network>
  <name>meta-platform-spire-child</name>
  <dns enable='yes'>
    <host ip='172.16.127.250'>
      <hostname>meta-platform-vault-downstream-frontend.production.homelab-infra.dev</hostname>
      <hostname>vault-downstream.production.homelab-infra.dev</hostname>
    </host>
    <host ip='172.16.128.250'>
      <hostname>harbor-origin.production.homelab-infra.dev</hostname>
      <hostname>meta-platform-harbor-origin-frontend.production.homelab-infra.dev</hostname>
    </host>
    <host ip='10.0.0.5'>
      <hostname>other-project-node.example.dev</hostname>
    </host>
  </dns>
</network>`

func mustParseAddr(t *testing.T, s string) netip.Addr {
	t.Helper()
	addr, err := netip.ParseAddr(s)
	if err != nil {
		t.Fatalf("parse %s: %v", s, err)
	}
	return addr
}

// assertRecords fails unless got equals want by address and by host names in order.
func assertRecords(t *testing.T, got, want []Record) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("records = %+v, want %+v", got, want)
	}
	for i := range got {
		if got[i].IP != want[i].IP || !slices.Equal(got[i].Hostnames, want[i].Hostnames) {
			t.Fatalf("record %d = %+v, want %+v", i, got[i], want[i])
		}
	}
}

func TestParseDNSRecords_FiltersByProjectPrefix(t *testing.T) {
	got, err := ParseDNSRecords(networkXML, prefix)
	if err != nil {
		t.Fatalf("ParseDNSRecords: %v", err)
	}
	assertRecords(t, got, []Record{
		{mustParseAddr(t, "172.16.127.250"), []string{
			"meta-platform-vault-downstream-frontend.production.homelab-infra.dev",
			"vault-downstream.production.homelab-infra.dev",
		}},
		{mustParseAddr(t, "172.16.128.250"), []string{
			"harbor-origin.production.homelab-infra.dev",
			"meta-platform-harbor-origin-frontend.production.homelab-infra.dev",
		}},
	})
}

